const IST_OFFSET_MIN = 330;

/**
 * Returns an ISO timestamp `days` from today (India time) at `hour:minute` IST,
 * so the sample listings always look current.
 */
function at(now: Date, days: number, hour = 10, minute = 0): string {
  const ist = new Date(now.getTime() + IST_OFFSET_MIN * 60 * 1000);
  const utcMs = Date.UTC(
    ist.getUTCFullYear(),
    ist.getUTCMonth(),
    ist.getUTCDate() + days,
    hour,
    minute - IST_OFFSET_MIN
  );
  return new Date(utcMs).toISOString();
}


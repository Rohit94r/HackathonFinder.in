export function createSampleHackathons(now: Date): Hackathon[] {
  return seeds.map(({ days, ...seed }) => {
    const [deadline, start, end, added] = days;
    const isContest = seed.type === 'coding-contest';
    return {
      ...seed,
      registrationDeadline: at(now, deadline, 23, 59),
      startDate: at(now, start, isContest ? 19 : 9),
      endDate: at(now, end, isContest ? 22 : 18),
      addedAt: at(now, added, 8),
      lastChecked: new Date(now.getTime() - 2 * 60 * 60 * 1000).toISOString(),
    };
  });
}
